_mode = "dark"


def current_mode() -> str:
    return _mode


def set_mode(mode: str) -> str:
    """Activate ``mode`` and refresh every token exported by this module."""
    global _mode
    candidate = str(mode or "").strip().lower()
    if candidate not in PALETTES:
        candidate = DEFAULT_MODE
    _mode = candidate
    globals().update(PALETTES[candidate])
    globals()["LOG_LEVELS"] = dict(_LOG_LEVELS[candidate])
    globals()["STATE_COLORS"] = {
        "PENDING": TEXT_DIM,
        "TTS_PROCESSING": BLUE,
        "TTS_DONE": SUCCESS,
        "VIDEO_PROCESSING": BLUE,
        "VIDEO_DONE": SUCCESS,
        "UPLOADING": WARNING,
        "UPLOAD_DONE": SUCCESS,
        "ERROR": DANGER,
    }
    globals()["VIDEO_STATE_COLORS"] = {
        "PENDING": TEXT_DIM,
        "PROCESSING": BLUE,
        "DONE": SUCCESS,
        "UPLOADING": WARNING,
        "UPLOAD_DONE": SUCCESS,
        "ERROR": DANGER,
    }
    return _mode


def icon_color(role: str) -> str:
    """Resolve an icon palette role such as ``accent`` or ``muted``."""
    return {
        "text": ICON_TEXT,
        "muted": ICON_MUTED,
        "accent": ICON_ACCENT,
        "success": ICON_SUCCESS,
        "warning": ICON_WARNING,
        "danger": ICON_DANGER,
        "white": ICON_WHITE,
        "disabled": ICON_DISABLED,
    }.get(str(role or "text"), ICON_TEXT)


